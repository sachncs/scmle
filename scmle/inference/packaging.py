"""A self-contained, hardened service folder for any bundle.

ONNX can express only some models. This path works for every one: the folder
holds the bundle, the exact environment it was built in, a server script and
a Dockerfile, so the same Python model that was validated is the one that
serves.

The folder is built to be deployed, not just to run:

* the base image is pinned by digest, with a placeholder that the build
  refuses until `build.sh` resolves it (`scmle.deploy.base_image`);
* the install is locked: `requirements.lock` is the exact runtime closure,
  installed with `--no-deps`, followed by `pip check`;
* the container runs as a non-root user, and the README and the deployment
  contract require a read-only root filesystem and resource limits;
* an SBOM and a signed provenance statement ship with it, and the service
  verifies the bundle signature, every file checksum and the provenance before
  it deserializes anything;
* `SCMLE_ENV=production` is the image default and refuses `SCMLE_TRUSTED`;
* the build context excludes credentials and is scanned for them.
"""

import json
import pathlib
import stat
from typing import Any

from scmle.contracts import errors

SERVER = '''\
"""Serves the bundled model over HTTP (generated by scmle package)."""

import os
import pathlib

from scmle.deploy import runtime

if __name__ == "__main__":
    runtime.run(pathlib.Path(__file__).parent, os.environ)
'''

DOCKERFILE = """\
# Generated by scmle package. Build with ./build.sh, which resolves BASE_IMAGE
# to a digest. The default is a placeholder on purpose: the build refuses it.
ARG BASE_IMAGE={image}@{placeholder}
FROM ${{BASE_IMAGE}}
ARG BASE_IMAGE
RUN case "${{BASE_IMAGE}}" in \\
      *@{placeholder}) \\
        echo "BASE_IMAGE is the placeholder: use ./build.sh" >&2; exit 1;; \\
      *@sha256:*) ;; \\
      *) echo "BASE_IMAGE must be pinned by digest" >&2; exit 1;; \\
    esac
ENV PYTHONDONTWRITEBYTECODE=1 \\
    PYTHONUNBUFFERED=1 \\
    PIP_NO_CACHE_DIR=1 \\
    PIP_DISABLE_PIP_VERSION_CHECK=1 \\
    SCMLE_ENV=production \\
    PORT=8000
RUN useradd --system --uid 10001 --user-group --no-create-home \\
      --shell /usr/sbin/nologin service
WORKDIR /service
COPY requirements.lock .
RUN pip install --no-cache-dir --no-deps -r requirements.lock && pip check
COPY --chown=root:root . .
USER 10001:10001
EXPOSE 8000
STOPSIGNAL SIGTERM
HEALTHCHECK --interval=10s --timeout=3s --start-period=60s --retries=3 \\
  CMD ["python", "-m", "scmle.deploy.runtime", "healthcheck"]
CMD ["python", "serve.py"]
"""

BUILD_SCRIPT = """\
#!/usr/bin/env bash
# Build, scan and attest the image. Needs Docker with buildx, network access
# to the registry and to the vulnerability database, and pip-audit.
# Set SCMLE_SIGNING_KEY to sign the image attestation.
set -euo pipefail
cd "$(dirname "$0")"
IMAGE="${{IMAGE:-{name}:{version}}}"
PLATFORM="${{PLATFORM:-linux/amd64}}"   # repeat with linux/arm64

python -m scmle.deploy.context check .
python -m scmle.deploy.base_image resolve --image {image} \\
  --output base-image.lock.json
BASE="$(python -m scmle.deploy.base_image argument \\
  --lock base-image.lock.json)"

docker buildx build --platform "$PLATFORM" \\
  --build-arg BASE_IMAGE="$BASE" \\
  --metadata-file build-metadata.json --load -t "$IMAGE" .

pip-audit --requirement requirements.lock --no-deps --disable-pip \\
  --format json --output scan.json || true
python -m scmle.deploy.vuln_gate scan.json --policy vuln-policy.json \\
  --sbom sbom.cdx.json

python -m scmle.deploy.attest image --folder . \\
  --metadata build-metadata.json --lock base-image.lock.json
echo "built, scanned and attested $IMAGE"
"""

README = """\
# {name} service

Model `{name}` (version {version}), built with scmle {scmle} on
Python {python}. Bundle digest: `{digest}`.

## Build

    ./build.sh

It scans the build context for credentials, resolves the base image to a
digest, builds, runs the vulnerability scan against `requirements.lock`,
applies the gate in `vuln-policy.json` and writes `image-attestation.json`
binding the image digest to `provenance.json`. Nothing here has been built or
scanned until you run it.

## Run

The image defaults to `SCMLE_ENV=production`: the bundle must be signed, the
provenance must verify and the signing key must be supplied from a secret
store, never baked into the image:

    docker run --rm -p 8000:8000 --read-only --tmpfs /tmp:size=64m \\
      --user 10001:10001 --cap-drop ALL --security-opt no-new-privileges \\
      --memory 512m --cpus 1 --pids-limit 256 \\
      --env SCMLE_SIGNING_KEY {name}:{version}

Outside a container: `pip install -r requirements.lock`, then
`SCMLE_SIGNING_KEY=... SCMLE_ENV=staging python serve.py`. Package the model
with a signing key (`SCMLE_SIGNING_KEY` when running `scmle package`).

## Endpoints

* `GET /livez`: the process is up.
* `GET /readyz`: 200 only after verify, load and warm-up; otherwise 503 with
  the reason. A bundle that is unsigned, modified or does not match its
  provenance never becomes ready.
* `GET /health`: model version, checksum and artifact digest.
* `GET /schema`: input schema, schema digest, request and response schemas,
  limits and policies.
* `POST /predict` (or `/v1/predict`) with `{{"records": [{{...}}]}}`:
  predictions with the model version and artifact digest; rows that break the
  schema get a 422 with the reason. See `docs/SERVICE_SLO.md` in the scmle
  repository for the limits.

Settings (environment): `PORT`, `HOST`, `SCMLE_MAX_CONCURRENT`,
`SCMLE_SCORING_TIMEOUT`, `SCMLE_MAX_REQUEST_BYTES`, `SCMLE_MAX_RECORDS`,
`SCMLE_ON_NULL`, `SCMLE_ON_UNSEEN`.

## Files

`requirements.txt` lists the direct pins; `requirements.lock` is the runtime
closure installed in the image; `environment.lock` lists every package of the
environment the model was built in; `sbom.cdx.json` is the CycloneDX SBOM;
`provenance.json` is the signed build statement the service checks at start.
"""


def lock_roots(info: Any) -> list[str]:
    """Distributions the service needs, by name."""
    return ["scmle", "scikit-learn", "pandas", *info.libraries]


def write_service(
    bundle: Any,
    destination: str | pathlib.Path,
    scmle_pin: str | None = None,
    signing_key: str | bytes | None = None,
) -> pathlib.Path:
    """Writes a deployable service folder for `bundle`.

    Args:
        bundle: A `ModelBundle`.
        destination: Folder to create (must not already hold a service).
        scmle_pin: Requirement line for the framework itself; defaults to
            the exact version that built the bundle.
        signing_key: HMAC key that signs the bundle and the provenance
            statement; defaults to `$SCMLE_SIGNING_KEY`. Without a key the
            folder is unsigned and refuses to load in production.

    Returns:
        The folder.

    Raises:
        ArtifactError: If the destination already holds a model.
    """
    # Imported here so that `python -m scmle.deploy.<tool>`, which the
    # generated build.sh runs, does not find its module already loaded by the
    # package import.
    from scmle.deploy import attest
    from scmle.deploy import base_image
    from scmle.deploy import context
    from scmle.deploy import lockfile
    from scmle.deploy import provenance
    from scmle.deploy import vuln_gate
    from scmle.governance import sbom

    root = pathlib.Path(destination)
    if (root / "model").exists():
        raise errors.ArtifactError(f"{root} already holds a service")
    root.mkdir(parents=True, exist_ok=True)
    bundle.save(root / "model", signing_key)
    info = bundle.info
    python_minor = ".".join(info.python.split(".")[:2])
    image = f"python:{python_minor}-slim"

    framework = scmle_pin or f"scmle=={info.scmle_version}"
    pins = [framework]
    pins += [f"scikit-learn=={info.sklearn}", f"pandas=={info.pandas}"]
    pins += [f"{name}=={version}" for name, version in info.libraries.items()]
    write_text(root / "requirements.txt", "\n".join(pins) + "\n")

    unresolved: list[str] = []
    closure = lockfile.runtime_closure(
        lock_roots(info),
        versions={
            **info.environment,
            "scikit-learn": info.sklearn,
            "pandas": info.pandas,
            **info.libraries,
            "scmle": info.scmle_version,
        },
        unresolved=unresolved,
    )
    header = [
        "scmle runtime lock: exact pins, install with --no-deps",
        f"python {info.python}; built on {info.platform or 'unknown'}",
    ]
    if unresolved:
        header.append(
            "dependencies not followed (not installed where this was "
            f"packaged): {', '.join(unresolved)}"
        )
    lock_text = lockfile.render(closure, header)
    if scmle_pin and "==" not in scmle_pin:
        lock_text = (
            "\n".join(
                scmle_pin if line.startswith("scmle==") else line
                for line in lock_text.splitlines()
            )
            + "\n"
        )
    write_text(root / "requirements.lock", lock_text)
    bundle.environment_lock(root / "environment.lock")
    write_text(root / "serve.py", SERVER)
    write_text(
        root / "Dockerfile",
        DOCKERFILE.format(image=image, placeholder=base_image.PLACEHOLDER),
    )
    write_text(root / ".dockerignore", context.dockerignore_text())
    build = root / "build.sh"
    write_text(
        build,
        BUILD_SCRIPT.format(
            name=info.model_name, version=info.model_version, image=image
        ),
    )
    build.chmod(build.stat().st_mode | stat.S_IXUSR)
    write_text(
        root / "vuln-policy.json",
        json.dumps(vuln_gate.DEFAULT_POLICY, indent=2) + "\n",
    )
    digest = provenance.bundle_digest(root / "model")
    service_sbom = sbom.build_service(
        closure,
        model_name=info.model_name,
        model_version=info.model_version,
        bundle_digest=digest,
        base_image=image,
        software_version=info.scmle_version,
    )
    write_text(
        root / "sbom.cdx.json", json.dumps(service_sbom, indent=2) + "\n"
    )
    attest.write_provenance(
        root,
        digest,
        builder=f"scmle package {info.scmle_version}",
        base_image=image,
        signing_key=signing_key,
    )
    write_text(
        root / "README.md",
        README.format(
            name=info.model_name,
            version=info.model_version,
            scmle=info.scmle_version,
            python=info.python,
            digest=digest,
        ),
    )
    return root


def write_text(path: pathlib.Path, text: str) -> None:
    """Writes UTF-8 text with Unix newlines."""
    path.write_text(text, encoding="utf-8", newline="\n")
